"""Generate docs/data_dictionary.md from the built gold (and silver) Delta tables.

PITCHLAKE_ROOT=./lakehouse python scripts/gen_data_dictionary.py
"""

from __future__ import annotations

from pathlib import Path

from pitchlake.gold.build import list_models
from pitchlake.pipeline import Pipeline

OUT = Path(__file__).resolve().parents[1] / "docs" / "data_dictionary.md"
SILVER = [
    "matches",
    "events",
    "lineups",
    "lineup_positions",
    "shot_freeze_frames",
    "frames_360",
    "xref_player",
]


def main() -> None:
    store = Pipeline.from_env("local").store
    lines = [
        "# Data dictionary",
        "",
        "_Generated by `scripts/gen_data_dictionary.py` from the Delta tables "
        "(UEFA Euro 2024 open data, full run incl. 360)._",
        "",
    ]
    lines += ["## Gold (star schema)", ""]
    for name, desc, _ in list_models():
        t = store.read("gold", name)
        lines += [
            f"### gold.{name}",
            "",
            f"{desc}  ",
            f"Rows: **{t.num_rows:,}**",
            "",
            "| column | type |",
            "|---|---|",
        ]
        lines += [f"| `{f.name}` | {f.type} |" for f in t.schema]
        lines.append("")
    lines += ["## Silver (selected)", ""]
    for name in SILVER:
        ds = store.dataset("silver", name)
        if ds is None:
            continue
        lines += [
            f"### silver.{name}",
            "",
            f"Rows: **{ds.count_rows():,}** · columns: {len(ds.schema)}",
            "",
            "<details><summary>columns</summary>",
            "",
            "| column | type |",
            "|---|---|",
        ]
        lines += [f"| `{f.name}` | {f.type} |" for f in ds.schema]
        lines += ["", "</details>", ""]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
